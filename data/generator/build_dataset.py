"""Step 5: quality gate + final splits + demo seed files + data card.

Inputs : data/raw/tickets_raw.parquet (specs + Gemini text)
Outputs: data/processed/{tickets,train,val,test}.parquet, seed_history.csv, stream_test.csv, DATA_CARD.md

Quality gate (rule based; an optional LLM-judge sample is a separate step):
  - empty / too short / too long text, or refusal-looking output
  - label leakage: text contains category names / 'priority' words / ticket ids
  - near-duplicates (MiniLM cosine > 0.97) among NON-incident tickets in the same split
"""
import re

import numpy as np
import pandas as pd

from data.generator.llm import ROOT, usage_totals

RAW = ROOT / "data/raw/tickets_raw.parquet"
OUT = ROOT / "data/processed"
# Only real leakage: enum-style label names, explicit "category:/priority:" labels, internal ids.
# (Plain words like "billing" / "high priority" / "I cannot" are normal customer language.)
LEAK = re.compile(r"(LOGIN_ACCESS|FEATURE_REQUEST|ACCOUNT_MANAGEMENT|DATA_PRIVACY|(?:category|priority)\s*:|RC-\d+|INC-\d+)")
REFUSAL = re.compile(r"(as an ai|as a language model|i(?:'m| am) sorry, but i (?:can(?:'|no)t|cannot) (?:assist|help|fulfil))", re.I)


def gate(df: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    n0 = len(df)
    text = df.subject + " " + df.body
    bad = {
        "too_short": df.body.str.split().str.len() < 5,
        "too_long": df.body.str.split().str.len() > 300,
        "empty_subject": df.subject.str.len() < 3,
        "short_resolution": df.resolution.str.split().str.len() < 8,
        "label_leak": text.str.contains(LEAK),
        "refusal": (text + " " + df.resolution).str.contains(REFUSAL),
    }
    drop = np.zeros(n0, bool)
    report = {}
    for k, m in bad.items():
        report[k] = int(m.sum())
        drop |= m.values
    return df[~drop].reset_index(drop=True), report


def near_dups(df: pd.DataFrame, thr: float = 0.97) -> pd.Series:
    from sentence_transformers import SentenceTransformer

    model = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2")
    emb = model.encode((df.subject + ". " + df.body).tolist(), batch_size=64, normalize_embeddings=True,
                       show_progress_bar=False)
    drop = np.zeros(len(df), bool)
    for split, idx in df.groupby("split").indices.items():
        cand = idx[df.incident_id.iloc[idx].isna().values]  # incident paraphrases are *meant* to be similar
        e = emb[cand]
        sims = e @ e.T
        np.fill_diagonal(sims, 0)
        for i, j in zip(*np.where(np.triu(sims) > thr)):
            if not drop[cand[i]]:
                drop[cand[j]] = True
    return pd.Series(drop, index=df.index)


def card(df: pd.DataFrame, gate_report: dict, n_dups: int, n_raw: int) -> str:
    def dist(col, sub=None):
        d = (df if sub is None else sub)[col].value_counts()
        return ", ".join(f"{k} {v}" for k, v in d.items())

    inc = df[df.incident_id.notna()]
    esc = df.groupby("split").escalated.mean().round(3).to_dict()
    return f"""# Data card: CloudDesk synthetic support tickets

Generated {pd.Timestamp.now(tz='UTC').date()} by `data/generator/*` (seeded specs -> Gemini text). Labels are known by construction.

## Size
- Raw generated: {n_raw}; after quality gate: {n_raw - sum(gate_report.values())}; after near-dup removal: {len(df)} (removed {n_dups})
- Gate drops: {gate_report}
- Splits (time-based): {dist('split')}
- Incident tickets: {len(inc)} across {inc.incident_id.nunique()} incidents (dedup ground truth)
- Root causes: {df.root_cause_id.nunique()} (retrieval ground truth: relevant = same root_cause_id)

## Label distributions
- Category: {dist('category')}
- Priority: {dist('priority')}
- Tier: {dist('customer_tier')}
- Product: {dist('product')}
- Escalated rate by split: {esc}; overall {df.escalated.mean():.3f}; SLA breached {df.sla_breached.mean():.3f}

## Known limitations (be honest in the report)
- Text is LLM-written: cleaner and more homogeneous than real tickets, so absolute scores are optimistic.
- Escalation/SLA outcomes come from a known latent function + noise, so ROC-AUC measures recovery of that function,
  not real-world escalation behaviour.
- Some root causes sit on category boundaries (e.g. API 403 filed under LOGIN_ACCESS): intentional label noise.
- Tone (e.g. "angry") is only weakly expressed by some generator models.
- Text generated by several Gemini models rotating on a free-tier quota (per-batch model recorded in the LLM cache).

## LLM usage (all generation calls, incl. root causes)
{usage_totals()}
"""


def main():
    raw = pd.read_parquet(RAW)
    n_raw = len(raw)
    df, rep = gate(raw)
    print("gate:", rep, "->", len(df))
    dup = near_dups(df)
    df = df[~dup].reset_index(drop=True)
    print("near-dups removed:", int(dup.sum()), "->", len(df))

    OUT.mkdir(parents=True, exist_ok=True)
    df["text"] = df.subject + "\n" + df.body
    df["is_history"] = df.split.isin(["train", "val"])  # RAG corpus; test tickets are the live queries
    df.to_parquet(OUT / "tickets.parquet")
    for s in ["train", "val", "test"]:
        df[df.split == s].to_parquet(OUT / f"{s}.parquet")

    hist_cols = ["ticket_uid", "created_at", "customer_id", "customer_tier", "product", "subject", "body", "resolution",
                 "category", "priority", "root_cause_id"]
    df[df.is_history][hist_cols].to_csv(OUT / "seed_history.csv", index=False)
    stream_cols = ["ticket_uid", "created_at", "customer_id", "customer_tier", "product", "subject", "body"]
    df[df.split == "test"].sort_values("created_at")[stream_cols].to_csv(OUT / "stream_test.csv", index=False)

    (ROOT / "data/DATA_CARD.md").write_text(card(df, rep, int(dup.sum()), n_raw), encoding="utf-8")
    print("wrote", OUT, "and data/DATA_CARD.md")


if __name__ == "__main__":
    main()
